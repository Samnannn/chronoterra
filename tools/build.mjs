// CHRONOTERRA static-site generator.  Usage: node tools/build.mjs
// Writes all HTML pages and assets/js/data.js into the project root.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { destinations, journal } from './content.mjs';
import { homePage, destinationsPage, destinationDetail } from './pages1.mjs';
import {
  advisoriesPage, bookingPage, dataJs, journalPage, journalArticle, packingPage, faqPage, creditsPage, usedFor,
} from './pages2.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = (file, content) => {
  fs.mkdirSync(path.dirname(path.join(root, file)), { recursive: true });
  fs.writeFileSync(path.join(root, file), content);
};

const files = {
  'index.html': homePage(),
  'destinations.html': destinationsPage(),
  'advisories.html': advisoriesPage(),
  'booking.html': bookingPage(),
  'journal.html': journalPage(),
  'packing.html': packingPage(),
  'faq.html': faqPage(),
  'credits.html': creditsPage(),
  'assets/js/data.js': dataJs(),
};
const credits = JSON.parse(fs.readFileSync(path.join(root, 'tools/credits.json'), 'utf8'));
const rows = Object.entries(usedFor).filter(([k]) => credits[k]).map(([k, use]) => {
  const c = credits[k];
  return `| [${c.title.replace(/_/g, ' ')}](${c.page}) | ${c.author || 'Unknown'} | ${c.licenseUrl ? `[${c.license}](${c.licenseUrl})` : c.license} | ${use} |`;
});
files['CREDITS.md'] = `# Credits

CHRONOTERRA is a **fictional** tourism board created for the Autumn of Code Website Design Competition.
No photograph on the site was taken by the project team. All images are real photographs or artefacts from
[Wikimedia Commons](https://commons.wikimedia.org/), used under the open licences listed below, and shown as
stand-ins for imagined destinations. Every image caption or alt text says what it actually depicts.

## Photography

All images were resized, cropped and colour-graded for this site (adaptations). The homepage hero
(\`assets/img/hero-*.jpg\`) is a **composite artwork** made from three of the images below (the Panch Mahal,
the Milky Way and a supertree photograph); because two of its sources are CC BY-SA 4.0, the hero composite is
shared under [CC BY-SA 4.0](https://creativecommons.org/licenses/by-sa/4.0/).

| Work (Wikimedia Commons) | Author | Licence | Used for |
| --- | --- | --- | --- |
${rows.join('\n')}

## Typefaces (self-hosted, SIL Open Font Licence 1.1)

- **Instrument Serif** by Rodrigo Fuenzalida & Jordan Egstad
- **Hanken Grotesk** by Hanken Design Co.
- **IBM Plex Mono** by IBM

## Everything else

All copy, layout, SVG artwork (logo mark, expedition stamps, temporal portal, orbit diagram), CSS and JavaScript
were written for this project. No third-party code, libraries or logos are used. Historical statements are
deliberately modest and labelled as context; all destinations marked as fiction are invented.

## Build tooling (not shipped to visitors)

Static pages are generated by a small Node script (\`tools/build.mjs\`). Image processing used Python with Pillow
and NumPy; screenshots were taken with Playwright.
`;
for (const d of destinations) files[`destination-${d.id}.html`] = destinationDetail(d);
for (const j of journal) files[`journal-${j.id}.html`] = journalArticle(j);

for (const [f, c] of Object.entries(files)) out(f, c);
console.log(`Built ${Object.keys(files).length} files.`);
